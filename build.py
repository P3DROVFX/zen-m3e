#!/usr/bin/env python3
"""Build M3 Expressive for Zen.

Generates:
  matugen/zen-m3e.css      matugen template (both palettes + shell mode)
  src/00-palette.css       fallback palette (used until matugen has run)
  src/01-shapes.css        polygon shapes with equal vertex counts (morphable)
  chrome.css               every src/*.css concatenated (Sine loads one file)
"""
