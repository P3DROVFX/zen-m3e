def menu_icons_block():
    lines = [
        "/* GENERATED by build.py (MENU_ICONS): Zen icons for menu items, shown in the badge. */",
    ]
    for icon, ids in MENU_ICONS.items():
        sel = ",\n".join(f"#{i} > .menu-icon" for i in ids)
        lines.append(
            f"{sel} {{\n  content: url(\"chrome://browser/skin/zen-icons/{icon}.svg\") !important;\n  visibility: visible !important;\n"
            f"  --m3e-icon-bg: color-mix(in srgb, currentColor 10%, transparent);\n}}"
        )
    return "\n".join(lines) + "\n"


def main():
    tpl = template()
    (ROOT / "matugen").mkdir(exist_ok=True)
    (ROOT / "matugen" / "zen-m3e.css").write_text(tpl)
    if "--no-matugen" not in sys.argv:
        # The fallback sits in a layer so the unlayered colors.css import always wins.
        fb = fallback_palette(tpl) + "\n" + roles_block()
        cut = fb.index('@media -moz-pref("m3e.scheme", "system")')
        (SRC / "00-palette.css").write_text(
            "@layer m3e-fallback {\n" + fb[:cut].rstrip() + "\n}\n\n/* Forced by the m3e.scheme preference. */\n" + fb[cut:]
        )
    (SRC / "01-shapes.css").write_text(shapes_block())
    (SRC / "08-menu-icons.css").write_text(menu_icons_block())

    header = (
        "/*\n"
        " * M3 Expressive for Zen — https://github.com/P3DROVFX/zen-m3e\n"
        " * GENERATED by build.py from src/*.css. Edit the sources, then run ./build.py.\n"
        " */\n\n"
        "/* Live palette written by matugen next to this file (see install.sh). */\n"
        '@import url("colors.css");\n\n'
    )
    parts = []
    for f in sorted(SRC.glob("*.css")):
        parts.append(f"/* ===== {f.name} ===== */\n" + f.read_text().strip() + "\n")
    (ROOT / "chrome.css").write_text(header + "\n".join(parts))
    print(f"chrome.css: {(ROOT / 'chrome.css').stat().st_size / 1024:.1f} KiB from {len(parts)} files")


if __name__ == "__main__":
    main()
